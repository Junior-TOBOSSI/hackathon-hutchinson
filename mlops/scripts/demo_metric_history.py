"""SIMULATED metric curve, to explain ``mlflow.log_metric(key, value, step=...)``.

    python -m mlops.scripts.demo_metric_history

⚠️ The values are generated by a formula, NOT by a training. They go to a SEPARATE
experiment (``argos-foundation-demo-simulated-curves``), tagged ``simulated_curve=true``,
so they can never be mistaken for the real runs of ``argos-foundation-demo``.
"""

from __future__ import annotations

import math
import random
import sys

import mlflow

from mlops.config import MlflowSettings, utf8_console

EXPERIMENT = "argos-foundation-demo-simulated-curves"


def main() -> int:
    utf8_console()
    settings = MlflowSettings.from_env()
    settings.apply_http_policy()
    mlflow.set_tracking_uri(settings.tracking_uri)
    experiment = mlflow.set_experiment(EXPERIMENT)
    mlflow.MlflowClient().set_experiment_tag(experiment.experiment_id, "simulated_curve", "true")
    rng = random.Random(0)
    with mlflow.start_run(run_name="SIMULATED-metric-history-demo") as run:
        mlflow.set_tags(
            {
                "synthetic": "true",
                "simulated_curve": "true",
                "argos.note": "Formula-generated values to illustrate step-based metrics. "
                "Not a training.",
            }
        )
        for step in range(50):
            loss = 1.2 * math.exp(-step / 12) + 0.05 + rng.gauss(0, 0.01)
            mlflow.log_metric("simulated_loss", loss, step=step)
        print(f"Run {run.info.run_id}: 50 points of 'simulated_loss' logged with step=0..49")
    return 0


if __name__ == "__main__":
    sys.exit(main())
