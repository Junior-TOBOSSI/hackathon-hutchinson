"""DBX-05: deterministic SYNTHETIC 3-class dataset for the technical test of the Quality
YOLO pipeline (``quality-synthetic-3c``). Nothing here comes from Hutchinson data.

    python -m mlops.datasets_prep.quality_synthetic_3c prepare
    python -m mlops.datasets_prep.quality_synthetic_3c import --api http://127.0.0.1:8020/api \
        --i-have-explicit-authorization      # ONLY after explicit authorization

- JPG, 126 x 86 px (size of the real camera photos), classes OK / NOK_SANS / NOK_DOUBLE:
  a groove (ring) with exactly one joint (OK), no joint (NOK_SANS) or two joints (NOK_DOUBLE);
- bursts: one synthetic part photographed several times with small variations (offset,
  brightness, noise), recorded as ``group`` (S00, S01...);
- split BY BURST (a burst is never in two splits): per class 4 bursts train, 1 val, 1 test;
- same seed -> same bytes (JPEG encoding of Pillow is deterministic).

The goal is to exercise the pipeline end to end, not to obtain good scores.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

SEED = 2026
WIDTH, HEIGHT = 126, 86
CLASSES = ["OK", "NOK_SANS", "NOK_DOUBLE"]
BURSTS_PER_CLASS = {"train": 4, "validation": 1, "test": 1}
PHOTOS_PER_BURST = 6
FAMILY = {
    "dataset_id": "quality-synthetic-3c",
    "name": "Qualité — synthétique 3 classes (recette YOLO)",
    "use_case": "quality",
    "classes": CLASSES,
    "synthetic": True,
    "description": "Synthetic groove images (1, 0 or 2 joints) with bursts, generated by "
    "mlops/datasets_prep/quality_synthetic_3c.py (seed 2026). Technical test only.",
}
VERSION = "v1"
HOME = Path(os.environ.get("ARGOS_MLOPS_HOME", Path.home() / "ARGOS_MLOPS_LOCAL"))
OUT = HOME / "prep" / "quality-synthetic-3c" / VERSION


def render(label: str, part: dict, rng: np.random.Generator) -> bytes:
    """One photo of one synthetic part (the part's joints are fixed, the shot varies)."""
    img = Image.new("L", (WIDTH, HEIGHT), int(part["background"]))
    draw = ImageDraw.Draw(img)
    dx, dy = int(rng.integers(-3, 4)), int(rng.integers(-3, 4))
    cx, cy, r = WIDTH // 2 + dx, HEIGHT // 2 + dy, 30
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], outline=200, width=4)  # groove
    for angle in part["joints"]:
        draw.arc(
            [cx - r + 3, cy - r + 3, cx + r - 3, cy + r - 3], angle, angle + 70, fill=250, width=5
        )
    pixels = np.asarray(img, dtype=np.float32) * float(rng.uniform(0.8, 1.05))
    pixels += rng.normal(0, 6.0, pixels.shape)
    out = io.BytesIO()
    Image.fromarray(np.clip(pixels, 0, 255).astype(np.uint8), mode="L").convert("RGB").save(
        out, format="JPEG", quality=92
    )
    return out.getvalue()


def generate() -> dict:
    rng = np.random.default_rng(SEED)
    items, blobs, burst = [], {}, 0
    for label in CLASSES:
        for split, n_bursts in BURSTS_PER_CLASS.items():
            for _ in range(n_bursts):
                n_joints = {"OK": 1, "NOK_SANS": 0, "NOK_DOUBLE": 2}[label]
                part = {
                    "background": int(rng.integers(30, 70)),
                    "joints": [int(a) for a in rng.integers(0, 360, n_joints)],
                }
                group = f"S{burst:02d}"
                for k in range(PHOTOS_PER_BURST):
                    data = render(label, part, rng)
                    name = f"syn3c_{group}_{k:02d}.jpg"
                    blobs[name] = data
                    items.append(
                        {
                            "name": name,
                            "label": label,
                            "split": split,
                            "group": group,
                            "sha256": hashlib.sha256(data).hexdigest(),
                        }
                    )
                burst += 1
    counts = {
        s: {c: sum(1 for i in items if i["split"] == s and i["label"] == c) for c in CLASSES}
        for s in BURSTS_PER_CLASS
    }
    return {
        "family": FAMILY,
        "version": VERSION,
        "seed": SEED,
        "split_strategy": "by_burst (group)",
        "counts": counts,
        "items": items,
        "blobs": blobs,
    }


def prepare() -> int:
    plan = generate()
    for i in plan["items"]:
        path = OUT / "images" / i["split"] / i["label"] / i["name"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(plan["blobs"][i["name"]])
    public = {k: v for k, v in plan.items() if k != "blobs"}
    (OUT / "plan.json").write_text(json.dumps(public, indent=2), encoding="utf-8")
    print(f"{len(plan['items'])} synthetic images in {OUT}")
    print("counts:", json.dumps(plan["counts"]))
    return 0


def import_plan(api: str) -> int:
    from mlops.datasets_prep.presse_5s import _call

    plan = generate()
    fam = FAMILY["dataset_id"]
    if fam not in {f["dataset_id"] for f in _call(api, "GET", "/mlops/datasets")}:
        _call(
            api,
            "POST",
            "/mlops/datasets",
            {
                k: FAMILY[k]
                for k in ("dataset_id", "name", "use_case", "classes", "synthetic", "description")
            },
        )
    draft = _call(api, "POST", f"/mlops/datasets/{fam}/drafts", {"parent_version": None})
    did = draft["draft_id"]
    for group in sorted({i["group"] for i in plan["items"]}):
        batch = [i for i in plan["items"] if i["group"] == group]
        label, split = batch[0]["label"], batch[0]["split"]
        res = _call(
            api,
            "POST",
            f"/mlops/datasets/{fam}/drafts/{did}/import",
            form={
                "fields": {
                    "label": label,
                    "split": split,
                    "synthetic_attested": "true",
                    "group": group,
                },
                "files": [(i["name"], plan["blobs"][i["name"]]) for i in batch],
            },
        )
        if any(not r["accepted"] for r in res):
            raise SystemExit(f"refused in {group}: {[r for r in res if not r['accepted']]}")
    job = _call(api, "POST", f"/mlops/datasets/{fam}/drafts/{did}/publish", {"version": VERSION})
    while job["state"] == "running":
        time.sleep(1)
        job = _call(api, "GET", f"/mlops/dataset-jobs/{job['job_id']}")
    print("publication:", job["state"], job.get("manifest_sha256") or job.get("error"))
    return 0 if job["state"] == "succeeded" else 1


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("command", choices=["prepare", "import"])
    p.add_argument("--api", default="http://127.0.0.1:8020/api")
    p.add_argument("--i-have-explicit-authorization", action="store_true")
    a = p.parse_args()
    if a.command == "prepare":
        return prepare()
    if not a.i_have_explicit_authorization:
        raise SystemExit("import refused: explicit user authorization required")
    return import_plan(a.api)


if __name__ == "__main__":
    sys.exit(main())
